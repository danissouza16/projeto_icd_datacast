def normalizar_municipio(nome: str) -> str:
    if pd.isna(nome):
        return nome
    nome = str(nome).strip().upper()
    nome = unicodedata.normalize("NFKD", nome)
    nome = nome.encode("ascii", "ignore").decode("ascii")
    nome = re.sub(r"\s+", " ", nome)
    return nome

