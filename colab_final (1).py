# Matriz de confusão: Árvore de Decisão e Random Forest (sem SMOTE), previsão para o mesmo dia (k = 0)
from sklearn.metrics import ConfusionMatrixDisplay

def matriz(k, ano_teste):
    X, y, datas = prepara(comum, k)
    X = X.astype(float)
    ano = datas.dt.year.values
    tr, te = ano < ano_teste, ano == ano_teste
    imp = SimpleImputer(strategy="median", keep_empty_features=True).fit(X[tr])
    X_tr, X_te = imp.transform(X[tr]), imp.transform(X[te])
    arv = DecisionTreeClassifier(max_depth=3, min_samples_leaf=20,
                                 class_weight="balanced", random_state=42).fit(X_tr, y[tr])
    rf = RandomForestClassifier(n_estimators=300, min_samples_leaf=5, class_weight="balanced_subsample",
                                n_jobs=-1, random_state=42).fit(X_tr, y[tr])
    return y[te], {"Árvore de Decisão": arv.predict(X_te), "Random Forest": rf.predict(X_te)}

