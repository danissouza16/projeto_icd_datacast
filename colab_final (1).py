def arvore(k, ano_teste, profundidades=(3, 4, 5, 6, 8)):
  X, y, datas = prepara(comum, k)
  X = X.astype(float)
  ano = datas.dt.year.values

  def treina(mascara, prof):
    imp = SimpleImputer(strategy="median", keep_empty_features=True).fit(X[mascara])
    m = DecisionTreeClassifier(max_depth=prof, min_samples_leaf=20,
                               class_weight="balanced", random_state=42)
    m.fit(imp.transform(X[mascara]), y[mascara])
    return imp, m

  tr_sel, va = ano < ano_teste - 1, ano == ano_teste - 1
  melhor, melhor_f2 = profundidades[0], -1
  for d in profundidades:
    imp, m = treina(tr_sel, d)
    pred_va = m.predict(imp.transform(X[va]))
    f2 = fbeta_score(y[va], pred_va, beta=2, zero_division=0)
    if f2 > melhor_f2:
      melhor, melhor_f2 = d, f2

    tr, te = ano < ano_teste, ano == ano_teste
    imp, m = treina(tr, melhor)
    X_te = imp.transform(X[te])
    pred = m.predict(X_te)
    p = m.predict_proba(X_te)[:, 1]
    tn, fp, fn, tp = confusion_matrix(y[te], pred, labels=[0, 1]).ravel()
    return {"k": k, "teste": ano_teste, "profundidade": melhor,
            "cheias_teste": int(y[te].sum()),
            "acertou": int(tp), "perdeu": int(fn), "alarmes_falsos": int(fp),
            "recall": round(tp / max(tp + fn, 1), 3),
            "precisao": round(tp / max(tp + fp, 1), 3),
            "F2": round(fbeta_score(y[te], pred, beta=2, zero_division=0), 3),
            "AUC-PR": round(average_precision_score(y[te], p), 3)}

res_arvore = pd.DataFrame([arvore(0, a) for a in (2022, 2023, 2024)])
print(res_arvore.to_string(index=False))
res_arvore.to_csv(PASTA_PROJETO + "resultado_arvore.csv", index=False)

