def avalia(k, ano_teste, ratio=0.02, smote=True):
    X, y, datas = prepara(comum, k)
    X = X.astype(float)
    ano = datas.dt.year.values
    tr, te = ano < ano_teste, ano == ano_teste
    X_tr, y_tr, X_te, y_te = X[tr], y[tr], X[te], y[te]

    imp = SimpleImputer(strategy="median", keep_empty_features=True)
    X_tr_i = imp.fit_transform(X_tr)
    X_te_i = imp.transform(X_te)

    if smote:
        X_tr_i, y_tr = SMOTE(sampling_strategy=ratio, random_state=42).fit_resample(X_tr_i, y_tr)

    rf = RandomForestClassifier(n_estimators=300, min_samples_leaf=5,
                                class_weight="balanced_subsample",
                                n_jobs=-1, random_state=42).fit(X_tr_i, y_tr)
    p = rf.predict_proba(X_te_i)[:, 1]
    pred = (p >= 0.5).astype(int)
    return {"k": k, "teste": ano_teste, "smote": smote,
            "cheias_teste": int(y_te.sum()),
            "prevalencia": round(float(y_te.mean()), 4),
            "AUC-PR": round(average_precision_score(y_te, p), 3),
            "recall": round(recall_score(y_te, pred), 3),
            "precisao": round(precision_score(y_te, pred, zero_division=0), 3)}

